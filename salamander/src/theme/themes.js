export const DEFAULT_THEME = 'light'
export const THEME_NAMES = Object.keys(THEMES)

const cssVarName = (token) => '--' + token.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())

export function applyTheme(name) {
    const chosen = THEMES[name] ? name : DEFAULT_THEME
    const { colors, mode } = THEMES[chosen]
    const root = document.documentElement
    for (const [token, value] of Object.entries(colors)) {
        root.style.setProperty(cssVarName(token), value)
    }
    root.setAttribute('data-theme', chosen)
    root.style.colorScheme = mode
    return chosen
}

const KEY = 'salamander-theme'
export function getCachedTheme() {
    try { const v = localStorage.getItem(KEY); return THEMES[v] ? v : DEFAULT_THEME }
    catch { return DEFAULT_THEME }
}
export function cacheTheme(name) {
    try { localStorage.setItem(KEY, name) } catch { /* private mode: ignore */ }
}